    #[test]
    fn test_wildcard_match_and_source_expansion() {
        assert!(wildcard_match("*.cpp", "thermal.cpp"));
        assert!(!wildcard_match("*.cpp", "sub/thermal.cpp"));
        assert!(wildcard_match("**/*.cpp", "sub/thermal.cpp"));
        assert!(wildcard_match("**/*.cpp", "thermal.cpp"));
        assert!(wildcard_match("call_*.cpp", "call_ladder.cpp"));

        let tmp = tempfile::tempdir().unwrap();
        let selftest_dir = tmp.path().join("source/selftest");
        fs::create_dir_all(&selftest_dir).unwrap();
        fs::write(selftest_dir.join("call_ladder.cpp"), "int a;").unwrap();
        fs::write(selftest_dir.join("memory_ladder.cpp"), "int b;").unwrap();
        fs::write(selftest_dir.join("ignored.cpp"), "int c;").unwrap();

        // 1. Auto-discovery when sources is empty
        let auto = expand_target_sources(
            tmp.path(),
            "source/selftest",
            &[],
            &["ignored.cpp".to_string()],
        );
        assert_eq!(
            auto,
            vec![
                "source/selftest/call_ladder.cpp",
                "source/selftest/memory_ladder.cpp",
            ]
        );

        // 2. Wildcard pattern
        let globbed = expand_target_sources(
            tmp.path(),
            "source/selftest",
            &["call_*.cpp".to_string()],
            &[],
        );
        assert_eq!(globbed, vec!["source/selftest/call_ladder.cpp"]);
    }

    #[test]
    fn test_pure_function_executor_caches_across_mtime_changes_and_rebuilds_on_header_change() {
        let tmp = tempfile::tempdir().unwrap();
        let src_dir = tmp.path().join("src");
        let inc_dir = tmp.path().join("include");
        fs::create_dir_all(&src_dir).unwrap();
        fs::create_dir_all(&inc_dir).unwrap();

        fs::write(inc_dir.join("math_const.hpp"), "#pragma once\nconstexpr int kOffset = 10;\n")
            .unwrap();
        fs::write(
            src_dir.join("math.cpp"),
            "#include \"math_const.hpp\"\nint compute_val(int x) { return x + kOffset; }\n",
        )
        .unwrap();
        fs::write(
            src_dir.join("main.cpp"),
            "int compute_val(int);\nint main() { return compute_val(32) == 42 ? 0 : 1; }\n",
        )
        .unwrap();

        let manifest_src = r#"
            struct DemoPkg: Package {
                var targets: [Target] {
                    [
                        .target(
                            name: "math",
                            path: "src",
                            sources: ["math.cpp"],
                            cxxSettings: [.headerSearchPath("include")]
                        ),
                        .executableTarget(
                            name: "app",
                            path: "src",
                            sources: ["main.cpp"],
                            dependencies: ["math"]
                        ),
                    ]
                }
            }
        "#;
        let pkg = parse_package_swift(manifest_src).unwrap();
        let actions = build_action_graph(
            &pkg,
            tmp.path(),
            ".rbuild-out/native",
            Some("macOS"),
            Some("debug"),
            Some("clang++"),
            Some("ar"),
        );
        assert_eq!(actions.len(), 4); // compile math.cpp, archive libmath.a, compile main.cpp, link app

        // 1st run: Cold build -> executes all 4 actions
        let rep1 = execute_action_graph(tmp.path(), &actions).unwrap();
        assert_eq!(rep1.total_actions, 4);
        assert_eq!(rep1.executed_actions, 4);
        assert_eq!(rep1.cache_hits, 0);

        // 2nd run: Touch mtime of math.cpp WITHOUT changing content -> 100% cache hit!
        fs::write(
            src_dir.join("math.cpp"),
            "#include \"math_const.hpp\"\nint compute_val(int x) { return x + kOffset; }\n",
        )
        .unwrap();
        let rep2 = execute_action_graph(tmp.path(), &actions).unwrap();
        assert_eq!(rep2.executed_actions, 0);
        assert_eq!(rep2.cache_hits, 4);

        // 3rd run: Modify transitive header `include/math_const.hpp` (tracked via .d depfile!)
        // -> math.cpp, libmath.a, and app rebuild; main.cpp stays a cache hit!
        fs::write(inc_dir.join("math_const.hpp"), "#pragma once\nconstexpr int kOffset = 20;\n")
            .unwrap();
        let rep3 = execute_action_graph(tmp.path(), &actions).unwrap();
        assert_eq!(rep3.cache_hits, 1); // main.cpp.o is a cache hit!
        assert_eq!(rep3.executed_actions, 3); // math.cpp.o, libmath.a, app re-executed!
    }
