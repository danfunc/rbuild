/// Canonical identity of a build tool (compiler, archiver, linker, converter).
///
/// Instead of hashing the host-specific binary path (e.g. `/opt/homebrew/bin/arm-none-eabi-g++`
/// on macOS vs `/usr/bin/arm-none-eabi-g++` on Linux), `ToolIdentity` captures the logical tool
/// family and its semantic version string so identical compiler versions produce identical cache keys
/// across platforms and paths.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ToolIdentity {
    pub logical_name: String,
    pub version_signature: String,
}

/// Kind of build action in the execution graph.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ActionKind {
    Compile,
    Archive,
    Link,
    ConvertUf2,
    CodeSign,
    CustomSideEffect,
}

/// A single node in the Ninja-equivalent build DAG.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct BuildAction {
    pub id: String,
    pub target_name: String,
    pub kind: ActionKind,
    pub program: String,
    pub tool_identity: ToolIdentity,
    pub args: Vec<String>,
    pub inputs: Vec<String>,
    pub outputs: Vec<String>,
    /// Optional Makefile-style `.d` depfile path generated by `-MMD -MF <depfile>`.
    pub depfile: Option<String>,
    /// Whether this action has external side effects (e.g. code signing, hardware flash, timestamping)
    /// and therefore must not be skipped by pure-function output caching.
    pub has_side_effects: bool,
}

/// Stored record in `.rbuild/action_cache/<primary_key>.json`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct CachedActionRecord {
    pub primary_key: String,
    pub tool_identity: ToolIdentity,
    pub args: Vec<String>,
    /// `(relative_path, blake3_hex)` of explicit inputs.
    pub explicit_inputs: Vec<(String, String)>,
    /// `(path, blake3_hex)` of transitive header dependencies discovered from `.d` depfile.
    pub discovered_deps: Vec<(String, String)>,
    /// `(output_relative_path, cas_blob_blake3_hex)` of produced outputs stored in `.rbuild/cas/`.
    pub outputs: Vec<(String, String)>,
}

/// Summary statistics from executing a build graph.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct BuildExecutionReport {
    pub total_actions: usize,
    pub cache_hits: usize,
    pub executed_actions: usize,
    pub side_effect_actions_run: usize,
    pub elapsed_ms: u128,
    pub built_outputs: Vec<String>,
}

/// Probes the canonical version identity of a compiler or tool binary.
pub fn probe_tool_identity(program: &str) -> ToolIdentity {
    let logical_name = Path::new(program)
        .file_name()
        .map(|s| s.to_string_lossy().to_string())
        .unwrap_or_else(|| program.to_string());

    // Try `-dumpfullversion -dumpversion` first for GCC/Clang cross-compilers (returns e.g. `15.3.1`)
    if logical_name.contains("gcc")
        || logical_name.contains("g++")
        || logical_name.contains("clang")
    {
        if let Ok(out) = Command::new(program)
            .args(["-dumpfullversion", "-dumpversion"])
            .output()
        {
            if out.status.success() {
                let ver = String::from_utf8_lossy(&out.stdout).trim().to_string();
                if !ver.is_empty() {
                    return ToolIdentity {
                        logical_name,
                        version_signature: ver,
                    };
                }
            }
        }
    }

    // Fallback to first line of `--version`
    if let Ok(out) = Command::new(program).arg("--version").output() {
        if out.status.success() {
            if let Some(first_line) = String::from_utf8_lossy(&out.stdout).lines().next() {
                let normalized = first_line.trim().to_string();
                if !normalized.is_empty() {
                    return ToolIdentity {
                        logical_name,
                        version_signature: normalized,
                    };
                }
            }
        }
    }

    ToolIdentity {
        logical_name,
        version_signature: "unknown".to_string(),
    }
}

/// Parses a GCC/Clang Makefile dependency file (`.d` generated by `-MMD -MF`) into a list of
/// prerequisite file paths, handling `\` line continuations and `\ ` escaped spaces.
pub fn parse_makefile_depfile(content: &str) -> Vec<String> {
    // Join backslash-newline continuations
    let mut joined = String::with_capacity(content.len());
    let mut chars = content.chars().peekable();
    while let Some(ch) = chars.next() {
        if ch == '\\' {
            if chars.peek() == Some(&'\n') {
                chars.next();
                joined.push(' ');
                continue;
            } else if chars.peek() == Some(&'\r') {
                chars.next();
                if chars.peek() == Some(&'\n') {
                    chars.next();
                }
                joined.push(' ');
                continue;
            }
        }
        joined.push(ch);
    }

    let mut deps = Vec::new();
    let mut seen = BTreeSet::new();

    for line in joined.lines() {
        let trimmed = line.trim();
        if trimmed.is_empty() || trimmed.starts_with('#') {
            continue;
        }
        // Find the target separator `:` (ignoring drive letters or escaped colons)
        let Some(colon_idx) = trimmed.find(':') else {
            continue;
        };
        let rhs = &trimmed[colon_idx + 1..];
        let mut current = String::new();
        let mut rchars = rhs.chars().peekable();
        while let Some(c) = rchars.next() {
            if c == '\\' {
                if let Some(&next_c) = rchars.peek() {
                    if next_c == ' ' || next_c == '#' || next_c == ':' || next_c == '\\' {
                        current.push(next_c);
                        rchars.next();
                        continue;
                    }
                }
                current.push(c);
            } else if c.is_whitespace() {
                if !current.is_empty() {
                    if seen.insert(current.clone()) {
                        deps.push(std::mem::take(&mut current));
                    } else {
                        current.clear();
                    }
                }
            } else {
                current.push(c);
            }
        }
        if !current.is_empty() && seen.insert(current.clone()) {
            deps.push(current);
        }
    }
    deps
}

/// Expands source paths for a target, supporting:
/// - Explicit relative paths (`"init.cpp"`)
/// - Wildcard patterns (`"*.cpp"`, `"**/*.cpp"`)
/// - Automatic directory source discovery when `sources` is empty
pub fn expand_target_sources(
    workspace_root: &Path,
    effective_path: &str,
    declared_sources: &[String],
    excludes: &[String],
) -> Vec<String> {
    let base_dir = workspace_root.join(effective_path);
    let exclude_set: BTreeSet<String> = excludes
        .iter()
        .map(|e| {
            if effective_path == "." || effective_path.is_empty() {
                e.clone()
            } else {
                format!("{effective_path}/{e}")
            }
        })
        .collect();

    let join_prefix = |rel: &str| -> String {
        if effective_path == "." || effective_path.is_empty() {
            rel.to_string()
        } else {
            format!("{effective_path}/{rel}")
        }
    };

    let mut result = Vec::new();
    let mut seen = BTreeSet::new();

    if declared_sources.is_empty() {
        if base_dir.is_dir() {
            let mut discovered = Vec::new();
            collect_source_files_recursive(&base_dir, &base_dir, &mut discovered);
            discovered.sort();
            for rel in discovered {
                let full_rel = join_prefix(&rel);
                if !exclude_set.contains(&full_rel) && seen.insert(full_rel.clone()) {
                    result.push(full_rel);
                }
            }
            if !result.is_empty() {
                return result;
            }
        }
        // Fallback when directory does not exist on disk yet (e.g. unit test virtual plans)
        let fallback_name = Path::new(effective_path)
            .file_name()
            .map(|s| s.to_string_lossy().to_string())
            .unwrap_or_else(|| "main".to_string());
        return vec![join_prefix(&format!("{fallback_name}.cpp"))];
    }

    for pattern in declared_sources {
        if pattern.contains('*') || pattern.contains('?') {
            if base_dir.is_dir() {
                let mut candidates = Vec::new();
                collect_source_files_recursive(&base_dir, &base_dir, &mut candidates);
                candidates.sort();
                for cand in candidates {
                    if wildcard_match(pattern, &cand) {
                        let full_rel = join_prefix(&cand);
                        if !exclude_set.contains(&full_rel) && seen.insert(full_rel.clone()) {
                            result.push(full_rel);
                        }
                    }
                }
            }
        } else {
            let full_rel = join_prefix(pattern);
            if !exclude_set.contains(&full_rel) && seen.insert(full_rel.clone()) {
                result.push(full_rel);
            }
        }
    }

    result
}

fn collect_source_files_recursive(root: &Path, current: &Path, out: &mut Vec<String>) {
    let Ok(entries) = fs::read_dir(current) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect_source_files_recursive(root, &path, out);
        } else if path.is_file() {
            if let Some(ext) = path.extension().and_then(|e| e.to_str()) {
                if matches!(ext, "c" | "cc" | "cpp" | "cxx" | "S" | "s") {
                    if let Ok(rel) = path.strip_prefix(root) {
                        out.push(rel.to_string_lossy().replace('\\', "/"));
                    }
                }
            }
        }
    }
}

/// Simple glob matcher supporting `*`, `**`, and `?`.
pub fn wildcard_match(pattern: &str, text: &str) -> bool {
    let pat_chars: Vec<char> = pattern.chars().collect();
    let txt_chars: Vec<char> = text.chars().collect();
    wildcard_match_inner(&pat_chars, &txt_chars)
}

fn wildcard_match_inner(pat: &[char], txt: &[char]) -> bool {
    if pat.is_empty() {
        return txt.is_empty();
    }
    if pat.len() >= 2 && pat[0] == '*' && pat[1] == '*' {
        let mut next_pat = &pat[2..];
        if next_pat.first() == Some(&'/') {
            next_pat = &next_pat[1..];
        }
        return wildcard_match_inner(next_pat, txt)
            || (!txt.is_empty() && wildcard_match_inner(pat, &txt[1..]));
    }
    if pat[0] == '*' {
        return wildcard_match_inner(&pat[1..], txt)
            || (!txt.is_empty() && txt[0] != '/' && wildcard_match_inner(pat, &txt[1..]));
    }
    if !txt.is_empty() && (pat[0] == '?' || pat[0] == txt[0]) {
        return wildcard_match_inner(&pat[1..], &txt[1..]);
    }
    false
}

/// Builds the complete execution DAG (`Vec<BuildAction>`) from a [`PackageManifest`].
pub fn build_action_graph(
    manifest: &PackageManifest,
    workspace_root: &Path,
    build_dir: &str,
    platform: Option<&str>,
    configuration: Option<&str>,
    cxx_override: Option<&str>,
    ar_override: Option<&str>,
) -> Vec<BuildAction> {
    let plan: Vec<ResolvedTargetPlan> = manifest.resolve_plan(platform, configuration);
    let is_rp2350 = platform.is_some_and(|p| p.eq_ignore_ascii_case("rp2350"));

    let cxx_prog = cxx_override
        .map(str::to_string)
        .or_else(|| std::env::var("CXX").ok())
        .unwrap_or_else(|| {
            if is_rp2350 {
                "arm-none-eabi-g++".to_string()
            } else {
                "clang++".to_string()
            }
        });
    let ar_prog = ar_override
        .map(str::to_string)
        .or_else(|| std::env::var("AR").ok())
        .unwrap_or_else(|| {
            if is_rp2350 {
                "arm-none-eabi-ar".to_string()
            } else {
                "ar".to_string()
            }
        });

    let cxx_identity = probe_tool_identity(&cxx_prog);
    let ar_identity = probe_tool_identity(&ar_prog);

    let mut actions = Vec::new();

    for (target_spec, target) in manifest.targets.iter().zip(plan.iter()) {
        let sources = expand_target_sources(
            workspace_root,
            &target.effective_path,
            &target.sources,
            &target_spec.exclude,
        );

        let mut obj_outputs = Vec::new();
        for src in &sources {
            let obj_rel = format!(
                "{build_dir}/obj/{}/{}.o",
                target.name,
                src.replace('/', "_")
            );
            let dep_rel = format!("{obj_rel}.d");
            let mut args = vec!["-MMD".to_string(), "-MF".to_string(), dep_rel.clone()];
            if src.ends_with(".c") {
                args.extend(target.c_flags.clone());
            } else {
                args.extend(target.cxx_flags.clone());
            }
            args.extend(["-c".to_string(), src.clone(), "-o".to_string(), obj_rel.clone()]);

            actions.push(BuildAction {
                id: format!("compile:{}:{src}", target.name),
                target_name: target.name.clone(),
                kind: ActionKind::Compile,
                program: cxx_prog.clone(),
                tool_identity: cxx_identity.clone(),
                args,
                inputs: vec![src.clone()],
                outputs: vec![obj_rel.clone()],
                depfile: Some(dep_rel),
                has_side_effects: false,
            });
            obj_outputs.push(obj_rel);
        }

        match target.kind {
            TargetKind::Regular => {
                let lib_rel = format!("{build_dir}/lib{}.a", target.name);
                let mut args = vec!["rcs".to_string(), lib_rel.clone()];
                args.extend(obj_outputs.clone());
                actions.push(BuildAction {
                    id: format!("archive:{}", target.name),
                    target_name: target.name.clone(),
                    kind: ActionKind::Archive,
                    program: ar_prog.clone(),
                    tool_identity: ar_identity.clone(),
                    args,
                    inputs: obj_outputs,
                    outputs: vec![lib_rel],
                    depfile: None,
                    has_side_effects: false,
                });
            }
            TargetKind::Executable | TargetKind::Test => {
                let mut link_inputs = obj_outputs;
                for dep in &target.dependencies {
                    if !dep.contains(':') {
                        link_inputs.push(format!("{build_dir}/lib{dep}.a"));
                    }
                }
                let bin_rel = if is_rp2350 {
                    format!("{build_dir}/{}.elf", target.name)
                } else {
                    format!("{build_dir}/{}", target.name)
                };
                let mut args = link_inputs.clone();
                args.extend(target.linker_flags.clone());
                args.extend(["-o".to_string(), bin_rel.clone()]);

                actions.push(BuildAction {
                    id: format!("link:{}", target.name),
                    target_name: target.name.clone(),
                    kind: ActionKind::Link,
                    program: cxx_prog.clone(),
                    tool_identity: cxx_identity.clone(),
                    args,
                    inputs: link_inputs,
                    outputs: vec![bin_rel.clone()],
                    depfile: None,
                    has_side_effects: false,
                });

                if let Some(fmt) = &target.output_format {
                    if fmt.starts_with("uf2") {
                        let uf2_rel = format!("{build_dir}/{}.uf2", target.name);
                        let family = fmt
                            .split_once('(')
                            .and_then(|(_, rest)| rest.strip_suffix(')'))
                            .unwrap_or("rp2350-arm-s");
                        let picotool_prog = std::env::var("PICOTOOL")
                            .unwrap_or_else(|_| "/opt/picotool/bin/picotool".to_string());
                        let picotool_id = probe_tool_identity(&picotool_prog);
                        actions.push(BuildAction {
                            id: format!("uf2:{}", target.name),
                            target_name: target.name.clone(),
                            kind: ActionKind::ConvertUf2,
                            program: picotool_prog,
                            tool_identity: picotool_id,
                            args: vec![
                                "uf2".to_string(),
                                "convert".to_string(),
                                "-t".to_string(),
                                "elf".to_string(),
                                bin_rel.clone(),
                                uf2_rel.clone(),
                                "--family".to_string(),
                                family.to_string(),
                            ],
                            inputs: vec![bin_rel],
                            outputs: vec![uf2_rel],
                            depfile: None,
                            has_side_effects: false,
                        });
                    }
                }
            }
            _ => {}
        }
    }

    actions
}

/// Computes the BLAKE3 hash of a file on disk, using [`ManifestCache`] `(size, mtime)` fast-path
/// when available so unchanged headers/sources do not even need to be re-read if mtime matches,
/// while still guaranteeing content-based caching when mtime changes.
fn hash_file_cached(workspace_root: &Path, rel_or_abs: &str, cache: &mut ManifestCache) -> Result<String> {
    let full_path = if Path::new(rel_or_abs).is_absolute() {
        PathBuf::from(rel_or_abs)
    } else {
        workspace_root.join(rel_or_abs)
    };
    let meta = fs::metadata(&full_path)
        .with_context(|| format!("Inspecting input file '{}'", full_path.display()))?;
    let size = meta.len();
    let mtime = meta.modified().unwrap_or(std::time::SystemTime::UNIX_EPOCH);
    let dur = mtime
        .duration_since(std::time::SystemTime::UNIX_EPOCH)
        .unwrap_or_default();
    let mtime_secs = dur.as_secs() as i64;
    let mtime_nanos = dur.subsec_nanos();

    if let Some(entry) = cache.entries.get(rel_or_abs) {
        if entry.size == size
            && entry.mtime_secs == mtime_secs
            && entry.mtime_nanos == mtime_nanos
        {
            return Ok(entry.blake3_hash.clone());
        }
    }

    let bytes = fs::read(&full_path)
        .with_context(|| format!("Reading input file '{}'", full_path.display()))?;
    let hash = blake3::hash(&bytes).to_hex().to_string();
    cache.entries.insert(
        rel_or_abs.to_string(),
        crate::sync::manifest::CacheEntry {
            size,
            mtime_secs,
            mtime_nanos,
            blake3_hash: hash.clone(),
        },
    );
    Ok(hash)
}

/// Computes the primary BLAKE3 key for a [`BuildAction`] based on its canonical [`ToolIdentity`],
/// command arguments, and content hashes of its explicit inputs.
pub fn compute_primary_action_key(
    action: &BuildAction,
    explicit_input_hashes: &[(String, String)],
) -> String {
    let mut hasher = blake3::Hasher::new();
    hasher.update(b"rbuild-action-v1\0");
    hasher.update(action.tool_identity.logical_name.as_bytes());
    hasher.update(b"\0");
    hasher.update(action.tool_identity.version_signature.as_bytes());
    hasher.update(b"\0");
    for arg in &action.args {
        hasher.update(arg.as_bytes());
        hasher.update(b"\0");
    }
    hasher.update(b"inputs:\0");
    for (path, hash) in explicit_input_hashes {
        hasher.update(path.as_bytes());
        hasher.update(b"=");
        hasher.update(hash.as_bytes());
        hasher.update(b"\0");
    }
    hasher.finalize().to_hex().to_string()
}

/// Executes a [`BuildAction`] DAG directly (Ninja-equivalent execution engine with BLAKE3 CAS).
pub fn execute_action_graph(
    workspace_root: &Path,
    actions: &[BuildAction],
) -> Result<BuildExecutionReport> {
    let start = Instant::now();
    let rbuild_dir = workspace_root.join(".rbuild");
    let action_cache_dir = rbuild_dir.join("action_cache");
    let cas_dir = rbuild_dir.join("cas");
    fs::create_dir_all(&action_cache_dir)?;
    fs::create_dir_all(&cas_dir)?;

    let manifest_cache_path = rbuild_dir.join("manifest_cache.json");
    let mut file_cache = ManifestCache::load_from_file(&manifest_cache_path);

    let mut report = BuildExecutionReport {
        total_actions: actions.len(),
        ..Default::default()
    };

    for action in actions {
        let mut explicit_hashes = Vec::with_capacity(action.inputs.len());
        for inp in &action.inputs {
            let h = hash_file_cached(workspace_root, inp, &mut file_cache)?;
            explicit_hashes.push((inp.clone(), h));
        }

        let primary_key = compute_primary_action_key(action, &explicit_hashes);
        let record_path = action_cache_dir.join(format!("{primary_key}.json"));

        // Check pure-function cache if the action is side-effect-free
        let mut cache_hit = false;
        if !action.has_side_effects && record_path.is_file() {
            if let Ok(bytes) = fs::read(&record_path) {
                if let Ok(record) = serde_json::from_slice::<CachedActionRecord>(&bytes) {
                    let deps_match = record.discovered_deps.iter().all(|(dep_path, expected_hash)| {
                        hash_file_cached(workspace_root, dep_path, &mut file_cache)
                            .map(|actual| &actual == expected_hash)
                            .unwrap_or(false)
                    });
                    let blobs_exist = record
                        .outputs
                        .iter()
                        .all(|(_, blob_hash)| cas_dir.join(blob_hash).is_file());

                    if deps_match && blobs_exist {
                        // Materialize outputs from CAS if missing or different on disk
                        for (out_rel, blob_hash) in &record.outputs {
                            let out_full = workspace_root.join(out_rel);
                            if let Some(parent) = out_full.parent() {
                                fs::create_dir_all(parent)?;
                            }
                            let needs_write = match hash_file_cached(workspace_root, out_rel, &mut file_cache) {
                                Ok(existing_hash) => &existing_hash != blob_hash,
                                Err(_) => true,
                            };
                            if needs_write {
                                fs::copy(cas_dir.join(blob_hash), &out_full)?;
                                // Refresh cache entry for materialized output
                                let _ = hash_file_cached(workspace_root, out_rel, &mut file_cache);
                            }
                            report.built_outputs.push(out_rel.clone());
                        }
                        report.cache_hits += 1;
                        cache_hit = true;
                    }
                }
            }
        }

        if cache_hit {
            continue;
        }

        // Prepare output directories
        for out_rel in &action.outputs {
            let out_full = workspace_root.join(out_rel);
            if let Some(parent) = out_full.parent() {
                fs::create_dir_all(parent)?;
            }
            if action.kind == ActionKind::Archive && out_full.exists() {
                let _ = fs::remove_file(&out_full);
            }
        }

        // Execute the command
        let output = Command::new(&action.program)
            .args(&action.args)
            .current_dir(workspace_root)
            .output()
            .with_context(|| {
                format!(
                    "Failed to spawn '{}' for action '{}'",
                    action.program, action.id
                )
            })?;

        if !output.status.success() {
            let stderr = String::from_utf8_lossy(&output.stderr);
            let stdout = String::from_utf8_lossy(&output.stdout);
            anyhow::bail!(
                "Action '{}' failed ({}):\n{} {}",
                action.id,
                output.status,
                stdout.trim(),
                stderr.trim()
            );
        }

        report.executed_actions += 1;
        if action.has_side_effects {
            report.side_effect_actions_run += 1;
        }

        // Parse `.d` depfile if produced
        let mut discovered_deps = Vec::new();
        let explicit_set: BTreeSet<&str> = action.inputs.iter().map(String::as_str).collect();
        if let Some(dep_rel) = &action.depfile {
            let dep_full = workspace_root.join(dep_rel);
            if let Ok(dep_content) = fs::read_to_string(&dep_full) {
                for dep_path in parse_makefile_depfile(&dep_content) {
                    if !explicit_set.contains(dep_path.as_str()) {
                        if let Ok(dep_hash) =
                            hash_file_cached(workspace_root, &dep_path, &mut file_cache)
                        {
                            discovered_deps.push((dep_path, dep_hash));
                        }
                    }
                }
            }
        }

        // Store outputs in CAS and record in Action Cache (unless side-effectful)
        let mut output_records = Vec::new();
        for out_rel in &action.outputs {
            let out_full = workspace_root.join(out_rel);
            let bytes = fs::read(&out_full).with_context(|| {
                format!(
                    "Expected output '{}' was not produced by action '{}'",
                    out_full.display(),
                    action.id
                )
            })?;
            let blob_hash = blake3::hash(&bytes).to_hex().to_string();
            if !action.has_side_effects {
                let blob_path = cas_dir.join(&blob_hash);
                if !blob_path.exists() {
                    fs::write(&blob_path, &bytes)?;
                }
            }
            // Refresh file_cache for the freshly built output
            file_cache.entries.remove(out_rel);
            let _ = hash_file_cached(workspace_root, out_rel, &mut file_cache);
            output_records.push((out_rel.clone(), blob_hash));
            report.built_outputs.push(out_rel.clone());
        }

        if !action.has_side_effects {
            let record = CachedActionRecord {
                primary_key,
                tool_identity: action.tool_identity.clone(),
                args: action.args.clone(),
                explicit_inputs: explicit_hashes,
                discovered_deps,
                outputs: output_records,
            };
            fs::write(&record_path, serde_json::to_vec_pretty(&record)?)?;
        }
    }

    let _ = file_cache.save_to_file(&manifest_cache_path);
    report.elapsed_ms = start.elapsed().as_millis();
    Ok(report)
}

